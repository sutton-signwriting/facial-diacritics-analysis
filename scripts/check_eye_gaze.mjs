import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';

const base = process.env.PREVIEW_URL || 'http://127.0.0.1:9123';
const options = {headless:true};
if (process.env.CHROMIUM_PATH) options.executablePath = process.env.CHROMIUM_PATH;
const browser = await chromium.launch(options);
const page = await browser.newPage({viewport:{width:1440,height:1100}});
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => {if (response.status()>=400) errors.push(`${response.status()} ${response.url()}`);});
const get = async path => (await fetch(base+path)).json();
await mkdir('artifacts', {recursive:true});
try {
  const [primary,gaze] = await Promise.all([get('/data/manifest.json'),get('/eye-gaze/data/manifest.json')]);
  assert.equal(primary.totals.rows,154755);
  assert.equal(primary.selection.min_diacritics,2);
  assert.equal(gaze.analysis_id,'eye-gaze-fills-2-3-v0.1');
  assert.equal(gaze.selection.min_diacritics,null);
  assert.deepEqual(gaze.selection.gaze_fills,[2,3]);
  assert.ok(gaze.histogram['1']>0,'Source selection must include one-diacritic signs');
  assert.ok(gaze.files.every(file=>!['sgn97','sgn103','sgn105'].includes(file.id)));
  await page.goto(base+'/');
  await page.locator('nav a').filter({hasText:'Eye gaze'}).click();
  await page.waitForSelector('.collections .file-link');
  assert.equal(await page.locator('#collection-kind').inputValue(),'nonempty');
  assert.equal(await page.locator('.collections tbody tr').count(),gaze.files.filter(file=>file.rows>0).length);
  await page.locator('#collection-kind').selectOption('all');
  assert.equal(await page.locator('.collections tbody tr').count(),gaze.files.length);
  await page.locator('#collection-kind').selectOption('nonempty');
  assert.ok((await page.locator('h1').textContent()).includes('fills 2 and 3'));
  const download = await page.locator('[download]').getAttribute('href');
  const csv = await (await fetch(new URL(download,page.url()))).text();
  assert.equal(csv.split('\n')[0],'fsw,fsw-face,uni-face,source_file,entry_id,source_offset,gaze-keys,gaze-positions');
  assert.equal(csv.trimEnd().split('\n').length,gaze.totals.rows+1);
  const info = gaze.files.find(f=>f.diacritics['1'] && f.mixed_gaze_fills && f.rows>25);
  assert.ok(info,'Need singleton and mixed-fill cases');
  const data = await get(`/eye-gaze/data/files/${info.id}.json`);
  assert.equal(data.records.length,info.rows);
  assert.ok(data.records.every(record=>/S32[1-9][23][0-9a-f][0-9]{3}x[0-9]{3}/.test(record.fsw)));
  await page.goto(base+`/eye-gaze/files/${info.id}.html`);
  await page.waitForSelector('.records .sign-view svg');
  assert.ok((await page.locator('.dataset-head .eyebrow').textContent()).includes('FILLS 2 AND 3'));
  assert.equal(await page.locator('#records tr').count(),25);
  assert.equal(await page.locator('#diacritics option[value="1"]').count(),1);
  await page.locator('#diacritics').selectOption('1');
  assert.ok((await page.locator('#records tr th .record-small').allTextContents()).filter(t=>t.endsWith('diacritic')).every(t=>t==='1 diacritic'));
  await page.locator('#diacritics').selectOption('all');
  await page.locator('#page-size').selectOption('all');
  assert.equal(await page.locator('#records tr').count(),info.rows);
  await page.locator('#gaze-fills').selectOption('selected');
  assert.equal(await page.locator('#records tr').count(),info.rows-info.mixed_gaze_fills);
  assert.ok(page.url().includes('gaze=selected'));
  await page.locator('#gaze-fills').selectOption('mixed');
  assert.equal(await page.locator('#records tr').count(),info.mixed_gaze_fills);
  const mixedLink = await page.locator('.row-number').first().getAttribute('href');
  await page.goto(mixedLink);
  await page.waitForSelector('#records tr');
  assert.equal(await page.locator('#gaze-fills').inputValue(),'mixed');
  assert.equal(await page.locator('#page-size').inputValue(),'all');
  await page.locator('.breadcrumb').click();
  await page.waitForSelector('.collections');
  assert.ok(new URL(page.url()).pathname.endsWith('/eye-gaze/index.html'));

  // The source-linked eye-gaze case is independently selected from the SPML.
  const known = await get('/eye-gaze/data/files/sgn114.json');
  const index = known.records.findIndex(r=>r.entry_id==='1920' && r.gaze_matches.some(s=>s.key==='S32127' && s.x===501 && s.y===491));
  assert.ok(index>=0);
  const row = index+1;
  await page.goto(base+`/eye-gaze/files/sgn114.html?rows=100&page=999#row-${row}`);
  await page.waitForSelector(`#row-${row} .sign-view svg`);
  assert.ok((await page.locator(`#row-${row} .gaze-key`).allTextContents()).some(t=>t.includes('S32127') && t.includes('501x491')));
  assert.equal(new URL(page.url()).searchParams.get('page'),row>100 ? String(Math.ceil(row/100)) : null);
  await page.locator('#page-size').selectOption('25');
  assert.equal(await page.locator(`#row-${row}`).count(),1);
  assert.equal(await page.locator('.render-error').count(),0);
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.goto(base+'/eye-gaze/');
  await page.waitForSelector('.collections');
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
  await page.screenshot({path:'artifacts/eye-gaze-mobile.png',fullPage:false});
  await page.locator('.text-link').click();
  await page.waitForSelector('#eye-gaze');
  assert.equal(errors.length,0,errors.join('\n'));
  console.log(`PASS: separate eye-gaze index and ${gaze.totals.rows} CSV records, one-diacritic signs, mixed-fill filters, All rows, deep links, known source case, fonts, methods, mobile, and unchanged primary count.`);
} finally {
  await browser.close();
}
